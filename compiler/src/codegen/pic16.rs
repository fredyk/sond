//! PIC16 backend, the mid-range 14-bit core (e.g. PIC16F684): the smallest target
//! profile, an 8-bit microcontroller with ~128 bytes of RAM and a 2K-word flash.
//!
//! Unlike the x86-64 codegen (a register machine with a data stack), the PIC14 core is
//! an accumulator (`W`) machine with banked file registers and only an 8-level hardware
//! CALL stack, so this is a SEPARATE, from-scratch emitter, not a reuse of `emit_all`.
//! It emits gpasm/MPASM assembly for a RESTRICTED Sond subset, assembled by
//! `gpasm -p p16f684` into a flashable Intel HEX.
//!
//! Phase 1 (this file) supports the subset that blinks an LED written in Sond:
//! `poke8(reg, val)` / `peek8(reg)` register I/O, an infinite `for { .. }` loop, and a
//! `delay()` builtin. Richer control flow, 8-bit arithmetic and locals come next.

use crate::ast::{Expr, Function, Stmt};
use std::collections::HashMap;

/// Folds an expression to an 8-bit constant, or `None` if it is not a compile-time
/// constant this minimal backend can place in a `movlw`.
fn const8(e: &Expr) -> Option<i64> {
    match e {
        Expr::Int(n) => Some(*n & 0xFF),
        Expr::Unary(crate::ast::UnOp::Neg, x) => const8(x).map(|v| (-v) & 0xFF),
        Expr::Binary(op, l, r) => {
            let (a, b) = (const8(l)?, const8(r)?);
            Some(
                match op {
                    crate::ast::BinOp::Add => a + b,
                    crate::ast::BinOp::Sub => a - b,
                    crate::ast::BinOp::BitOr => a | b,
                    crate::ast::BinOp::BitAnd => a & b,
                    crate::ast::BinOp::BitXor => a ^ b,
                    crate::ast::BinOp::Shl => a << b,
                    crate::ast::BinOp::Shr => a >> b,
                    _ => return None,
                } & 0xFF,
            )
        }
        _ => None,
    }
}

/// Emits a PIC16F684 assembly program for `funcs` (only `main` is compiled in Phase 1).
pub fn emit_pic16(funcs: &[Function]) -> String {
    let mut out = String::new();
    let mut lbl = 0usize;
    macro_rules! l {
        ($($a:tt)*) => {{ out.push_str(&format!($($a)*)); out.push('\n'); }};
    }
    l!("; Generated by sondc --pic16 (target: PIC16F684)");
    l!("        list    p=16f684");
    l!("        #include <p16f684.inc>");
    l!("        __CONFIG _INTOSCIO & _WDT_OFF & _PWRTE_ON & _MCLRE_OFF & _CP_OFF & _BOD_OFF");
    l!("        org     0x000");
    l!("        goto    main");
    l!("        org     0x004");
    l!("        retfie                  ; no interrupt handlers yet");
    // Allocate every function's parameters + locals to DISJOINT bank-0 RAM
    // (0x20..0x6F; 0x70+ is serial/delay scratch). Static allocation is sound
    // because Phase 1b has no recursion. Record each function's parameter
    // addresses so a call can drop its arguments into the callee's slots.
    let mut next = 0x20u8;
    let mut fn_locals: HashMap<String, HashMap<String, u8>> = HashMap::new();
    let mut fnp: HashMap<String, Vec<u8>> = HashMap::new();
    for f in funcs {
        let mut lm = HashMap::new();
        let mut params = Vec::new();
        for p in &f.params {
            lm.insert(p.name.clone(), next);
            params.push(next);
            next += 1;
        }
        collect_locals(&f.body, &mut lm, &mut next);
        fn_locals.insert(f.name.clone(), lm);
        fnp.insert(f.name.clone(), params);
    }

    l!("main:");
    if let Some(m) = funcs.iter().find(|f| f.name == "main") {
        emit_block(&m.body, &mut out, &mut lbl, &fn_locals[&m.name], &fnp, None);
    }
    l!("        goto    $               ; halt");

    // Every other function becomes a subroutine; its body's tail leaves the
    // return value in W, and a `call name` reaches it.
    for f in funcs {
        if f.name == "main" {
            continue;
        }
        l!("{}:", f.name);
        emit_block(&f.body, &mut out, &mut lbl, &fn_locals[&f.name], &fnp, None);
        l!("        return");
    }
    // A simple ~two-nested-loop busy delay (uses two GPRs at 0x70/0x71 in the common bank).
    // Ceded if the source defines its own `delay` (a user function of the same name wins).
    if !fnp.contains_key("delay") {
        l!("delay:");
        l!("        movlw   0xFF");
        l!("        movwf   0x70");
        l!("_dly1:  movlw   0xFF");
        l!("        movwf   0x71");
        l!("_dly2:  decfsz  0x71, f");
        l!("        goto    _dly2");
        l!("        decfsz  0x70, f");
        l!("        goto    _dly1");
        l!("        return");
    }
    // Bit-banged 9600-baud 8N1 UART on RA0 (TX). The 16F684 has no hardware UART, so this is
    // the physical layer of the PIC-cluster link (PC <-> CP2102 <-> PIC). BITDLY is tuned for
    // the internal oscillator at 8 MHz (~208 Tcy per bit); calibrate on real hardware if framing
    // is off (widen/narrow BITDLY by a few counts).
    l!("BITDLY  equ     0x41            ; ~one bit period at 8 MHz/9600 (calibrate on HW)");
    l!("HALFDLY equ     0x20            ; ~half a bit period (start-edge -> first-bit center)");
    if !fnp.contains_key("serial_init") {
        l!("serial_init:");
        l!("        banksel OSCCON");
        l!("        movlw   0x70            ; IRCF=111 -> 8 MHz internal oscillator");
        l!("        movwf   OSCCON");
        l!("        banksel ANSEL");
        l!("        clrf    ANSEL           ; all pins digital (ADC off)");
        l!("        banksel CMCON0");
        l!("        movlw   0x07            ; CM<2:0>=111");
        l!("        movwf   CMCON0          ; comparators off -> RA1 (C1IN-) is digital I/O");
        l!("        banksel VRCON");
        l!("        clrf    VRCON           ; CVref off (also shares RA1)");
        l!("        banksel TRISA");
        l!("        bcf     TRISA, 0        ; RA0 = TX = output");
        l!("        bsf     TRISA, 1        ; RA1 = RX = input");
        l!("        banksel PORTA");
        l!("        bsf     PORTA, 0        ; idle line high");
        l!("        return");
    }
    if !fnp.contains_key("serial_getc") {
        l!("serial_getc:                    ; receive one byte from RA1 (9600 8N1), return in W");
        l!("        clrf    0x75            ; result accumulator");
        l!("        movlw   0x08");
        l!("        movwf   0x76            ; bit count");
        l!("_sg_wait:                       ; wait for the start bit (line goes low)");
        l!("        banksel PORTA");
        l!("        btfsc   PORTA, 1");
        l!("        goto    _sg_wait");
        l!("        call    _halfdly        ; half a bit -> middle of the start bit (center sampling)");
        l!("_sg_bit:");
        l!("        call    _bitdly         ; advance ~one bit to the middle of this data bit");
        l!("        banksel PORTA");
        l!("        bcf     STATUS, 0       ; carry = sampled RX level");
        l!("        btfsc   PORTA, 1");
        l!("        bsf     STATUS, 0");
        l!("        rrf     0x75, f         ; shift carry into the byte, LSB first");
        l!("        decfsz  0x76, f");
        l!("        goto    _sg_bit");
        l!("        call    _bitdly         ; step over the stop bit");
        l!("        movf    0x75, w");
        l!("        return");
    }
    if !fnp.contains_key("serial_putc") {
        l!("serial_putc:                    ; transmit W as 9600 8N1, LSB first, on RA0");
        l!("        movwf   0x72            ; byte");
        l!("        movlw   0x08");
        l!("        movwf   0x73            ; bit count");
        l!("        banksel PORTA");
        l!("        bcf     PORTA, 0        ; start bit");
        l!("        call    _bitdly");
        l!("_sp_bit:");
        l!("        rrf     0x72, f         ; LSB -> C");
        l!("        btfss   STATUS, 0       ; C is bit 0 of STATUS");
        l!("        bcf     PORTA, 0");
        l!("        btfsc   STATUS, 0");
        l!("        bsf     PORTA, 0");
        l!("        call    _bitdly");
        l!("        decfsz  0x73, f");
        l!("        goto    _sp_bit");
        l!("        bsf     PORTA, 0        ; stop bit");
        l!("        call    _bitdly");
        l!("        return");
    }
    l!("_bitdly:");
    l!("        movlw   BITDLY");
    l!("        movwf   0x74");
    l!("_bd:    decfsz  0x74, f");
    l!("        goto    _bd");
    l!("        return");
    l!("_halfdly:                       ; ~half a bit period, to land on bit centers");
    l!("        movlw   HALFDLY");
    l!("        movwf   0x74");
    l!("_hd:    decfsz  0x74, f");
    l!("        goto    _hd");
    l!("        return");
    l!("_delayw:                        ; busy-loop W iterations (~3*W cycles); bit-bang timing");
    l!("        movwf   0x74");
    l!("_dw:    decfsz  0x74, f");
    l!("        goto    _dw");
    l!("        return");
    l!("        end");
    out
}

/// Recognises the call `name(args)` and returns `(name, args)`.
fn as_call(e: &Expr) -> Option<(&str, &[crate::ast::Arg])> {
    if let Expr::Call(callee, args) = e
        && let Expr::Var(name) = callee.as_ref()
    {
        return Some((name, args));
    }
    None
}

/// Assigns each `let`-bound name a fixed bank-0 RAM address (0x20 upward), recursing into loop
/// bodies and `if` branches. Phase-1b locals are STATIC (no data stack), apt for a small,
/// non-reentrant MCU program.
fn collect_locals(b: &crate::ast::Block, map: &mut HashMap<String, u8>, next: &mut u8) {
    let scan_if = |cond: &Expr, t: &crate::ast::Block, e: Option<&crate::ast::Block>, map: &mut HashMap<String, u8>, next: &mut u8| {
        let _ = cond;
        collect_locals(t, map, next);
        if let Some(eb) = e {
            collect_locals(eb, map, next);
        }
    };
    for s in &b.stmts {
        match s {
            Stmt::Let { name, .. } => {
                if !map.contains_key(name) {
                    map.insert(name.clone(), *next);
                    *next += 1;
                }
            }
            Stmt::For { body, .. } => collect_locals(body, map, next),
            Stmt::Expr(Expr::If {
                cond,
                then_branch,
                else_branch,
            }) => scan_if(cond, then_branch, else_branch.as_deref(), map, next),
            _ => {}
        }
    }
    if let Some(Expr::If {
        cond,
        then_branch,
        else_branch,
    }) = b.tail.as_deref()
    {
        scan_if(cond, then_branch, else_branch.as_deref(), map, next);
    }
}

/// Leaves the 8-bit value of `e` in W. Handles constants, locals, `serial_getc()`, and
/// `+`/`-`/`&`/`|`/`^` of two sub-expressions (via a temp at 0x7E).
/// Emits a call to a user-defined function: each argument is evaluated into W and
/// stored to the callee's fixed parameter slot, then `call name`. The callee
/// leaves its return value in W. `fnp` maps a function name to its parameter
/// register addresses (allocated disjointly, so there is no reentrancy hazard).
fn emit_user_call(
    name: &str,
    args: &[crate::ast::Arg],
    out: &mut String,
    locals: &HashMap<String, u8>,
    fnp: &HashMap<String, Vec<u8>>,
) {
    macro_rules! l {
        ($($a:tt)*) => {{ out.push_str(&format!($($a)*)); out.push('\n'); }};
    }
    let addrs = &fnp[name];
    for (i, arg) in args.iter().enumerate() {
        eval_to_w(&arg.value, out, locals, fnp);
        if let Some(&a) = addrs.get(i) {
            l!("        movwf   0x{a:02X}            ; arg {i} -> param");
        }
    }
    l!("        call    {name}");
}

fn eval_to_w(
    e: &Expr,
    out: &mut String,
    locals: &HashMap<String, u8>,
    fnp: &HashMap<String, Vec<u8>>,
) {
    macro_rules! l {
        ($($a:tt)*) => {{ out.push_str(&format!($($a)*)); out.push('\n'); }};
    }
    if let Some(c) = const8(e) {
        l!("        movlw   0x{:02X}", c & 0xFF);
        return;
    }
    match e {
        Expr::Var(v) => match locals.get(v) {
            Some(a) => l!("        movf    0x{a:02X}, w"),
            None => l!("        ; unknown local `{v}`"),
        },
        // Shift by a COMPILE-TIME CONSTANT: the PIC14 has no barrel shifter, so
        // emit N single-bit shifts. `<< 1` is a doubling (add to self); `>> 1` is
        // an rrf with carry pre-cleared. This is the generic primitive a Sond
        // bit-bang UART needs for rrf-style byte assembly (no variable shifts).
        Expr::Binary(op @ (crate::ast::BinOp::Shl | crate::ast::BinOp::Shr), a, b)
            if const8(b).is_some() =>
        {
            eval_to_w(a, out, locals, fnp);
            let n = (const8(b).unwrap() as usize).min(8); // >=8 on an 8-bit value is 0
            for _ in 0..n {
                l!("        movwf   0x7E");
                match op {
                    crate::ast::BinOp::Shl => l!("        addwf   0x7E, w         ; << 1"),
                    _ => {
                        l!("        bcf     STATUS, 0");
                        l!("        rrf     0x7E, w         ; >> 1");
                    }
                }
            }
        }
        Expr::Binary(op, a, b) => {
            eval_to_w(a, out, locals, fnp);
            l!("        movwf   0x7E            ; lhs");
            eval_to_w(b, out, locals, fnp);
            match op {
                crate::ast::BinOp::Add => l!("        addwf   0x7E, w         ; lhs + rhs"),
                crate::ast::BinOp::Sub => l!("        subwf   0x7E, w         ; lhs - rhs"),
                crate::ast::BinOp::BitAnd => l!("        andwf   0x7E, w"),
                crate::ast::BinOp::BitOr => l!("        iorwf   0x7E, w"),
                crate::ast::BinOp::BitXor => l!("        xorwf   0x7E, w"),
                // LOUD, not a comment. This used to emit `; unsupported operator` into the
                // assembly and carry on, so `sondc --pic16` exited 0 and produced a .hex with
                // the operation MISSING -- a firmware that flashes, runs, and computes something
                // else. On a microcontroller that is not a wrong number on a screen: it is a
                // motor step that never happens. `*`, `/`, `%` and the ordered comparisons are
                // the ones that land here today.
                other => panic!(
                    "PIC16 codegen does not implement the `{other:?}` operator yet. It is not \
                     emitted, so a program using it would flash and compute the wrong thing; \
                     write it with the operators the backend has (+ - & | ^ << >> == != <) or \
                     keep that arithmetic on the host side."
                ),
            }
        }
        _ => match as_call(e) {
            Some(("serial_getc", [])) => l!("        call    serial_getc"),
            // peek8(reg): read a register (e.g. an input port) into W. Needed for
            // reading pins — node-ID straps, an SPI-slave data line, RX bits.
            Some(("peek8", args)) if args.len() == 1 => {
                if let Some(r) = const8(&args[0].value) {
                    l!("        banksel 0x{:02X}", r & 0xFF);
                    l!("        movf    0x{:02X}, w", r & 0xFF);
                } else {
                    l!("        ; peek8 needs a constant register in Phase 1b");
                }
            }
            Some((name, args)) if fnp.contains_key(name) => {
                emit_user_call(name, args, out, locals, fnp)
            }
            _ => l!("        ; unsupported expression in Phase 1b"),
        },
    }
}

/// Emits a block: its statements, then its TAIL expression (Sond makes the last `if`/call in a
/// block the tail, not a statement, so an `if`-dispatch at the end of a loop body lives here).
fn emit_block(
    b: &crate::ast::Block,
    out: &mut String,
    lbl: &mut usize,
    locals: &HashMap<String, u8>,
    fnp: &HashMap<String, Vec<u8>>,
    le: Option<usize>,
) {
    for s in &b.stmts {
        emit_stmt(s, out, lbl, locals, fnp, le);
    }
    if let Some(tail) = &b.tail {
        match tail.as_ref() {
            Expr::If {
                cond,
                then_branch,
                else_branch,
            } => emit_if(cond, then_branch, else_branch.as_deref(), out, lbl, locals, fnp, le),
            e if as_call(e).is_some() => emit_call(e, out, locals, fnp),
            // A value tail is the block's result — for a function body it is the
            // return value, left in W.
            e => eval_to_w(e, out, locals, fnp),
        }
    }
}

fn emit_stmt(
    s: &Stmt,
    out: &mut String,
    lbl: &mut usize,
    locals: &HashMap<String, u8>,
    fnp: &HashMap<String, Vec<u8>>,
    le: Option<usize>,
) {
    macro_rules! l {
        ($($a:tt)*) => {{ out.push_str(&format!($($a)*)); out.push('\n'); }};
    }
    match s {
        Stmt::Let { name, value, .. } => {
            eval_to_w(value, out, locals, fnp);
            if let Some(a) = locals.get(name) {
                l!("        movwf   0x{a:02X}            ; let {name}");
            }
        }
        Stmt::Assign {
            target: Expr::Var(v),
            value,
        } => {
            eval_to_w(value, out, locals, fnp);
            if let Some(a) = locals.get(v) {
                l!("        movwf   0x{a:02X}            ; {v} =");
            }
        }
        // `for { .. }` with no condition, an infinite loop (the node's main dispatch loop).
        Stmt::For {
            cond: None, body, ..
        } => {
            let n = *lbl;
            *lbl += 1;
            l!("_loop{n}:");
            emit_block(body, out, lbl, locals, fnp, Some(n));
            l!("        goto    _loop{n}");
            l!("_end{n}:                          ; break target");
        }
        // `for lhs < rhs { .. }`: an 8-bit counted loop (unsigned), the basis of compute kernels
        // and reading a length-prefixed payload. `lhs = lhs + 1` in the body advances it.
        Stmt::For {
            cond: Some(Expr::Binary(crate::ast::BinOp::Lt, lhs, rhs)),
            body,
            ..
        } => {
            let n = *lbl;
            *lbl += 1;
            l!("_loop{n}:");
            eval_to_w(lhs, out, locals, fnp);
            l!("        movwf   0x7E            ; loop lhs");
            eval_to_w(rhs, out, locals, fnp);
            l!("        subwf   0x7E, w         ; lhs - rhs, C set iff lhs >= rhs");
            l!("        btfsc   STATUS, 0       ; C is bit 0");
            l!("        goto    _end{n}         ; lhs >= rhs -> exit");
            emit_block(body, out, lbl, locals, fnp, Some(n));
            l!("        goto    _loop{n}");
            l!("_end{n}:");
        }
        // `break`: jump to the enclosing loop's end label.
        Stmt::Break => match le {
            Some(n) => l!("        goto    _end{n}         ; break"),
            None => l!("        ; break outside a loop"),
        },
        // A statement-position `if x == C { .. } else { .. }`: the command dispatch.
        Stmt::Expr(Expr::If {
            cond,
            then_branch,
            else_branch,
        }) => emit_if(cond, then_branch, else_branch.as_deref(), out, lbl, locals, fnp, le),
        Stmt::Expr(e) => emit_call(e, out, locals, fnp),
        _ => l!("        ; (unsupported statement omitted in Phase 1b)"),
    }
}

/// Emits `if <lhs> == C { then } else { else }` (or `!=`), the byte-compare dispatch a
/// compute node needs. Other conditions are omitted (Phase 1b).
// The emit chain threads several read-only bits of context (locals, function
// table, enclosing loop); bundling them into a Ctx struct is a future cleanup.
#[allow(clippy::too_many_arguments)]
fn emit_if(
    cond: &Expr,
    then_b: &crate::ast::Block,
    else_b: Option<&crate::ast::Block>,
    out: &mut String,
    lbl: &mut usize,
    locals: &HashMap<String, u8>,
    fnp: &HashMap<String, Vec<u8>>,
    le: Option<usize>,
) {
    macro_rules! l {
        ($($a:tt)*) => {{ out.push_str(&format!($($a)*)); out.push('\n'); }};
    }
    let n = *lbl;
    *lbl += 1;
    if let Expr::Binary(op @ (crate::ast::BinOp::Eq | crate::ast::BinOp::Ne), lhs, rhs) = cond {
        // Leave W = lhs XOR rhs, so the Z flag is set iff the two are equal.
        if let Some(c) = const8(rhs) {
            eval_to_w(lhs, out, locals, fnp);
            l!("        xorlw   0x{:02X}            ; Z set iff equal", c & 0xFF);
        } else {
            // General comparison of two runtime values (e.g. a frame checksum
            // `calc == chk`): stash rhs in a scratch register, then XOR lhs in.
            eval_to_w(rhs, out, locals, fnp);
            l!("        movwf   0x7D            ; rhs of the comparison");
            eval_to_w(lhs, out, locals, fnp);
            l!("        xorwf   0x7D, w         ; Z set iff lhs == rhs");
        }
        // Eq: skip the then-branch when NOT equal; Ne: skip when equal.
        if matches!(op, crate::ast::BinOp::Eq) {
            l!("        btfss   STATUS, 2       ; STATUS Z is bit 2");
        } else {
            l!("        btfsc   STATUS, 2");
        }
        l!("        goto    _else{n}");
        emit_block(then_b, out, lbl, locals, fnp, le);
        l!("        goto    _endif{n}");
        l!("_else{n}:");
        if let Some(eb) = else_b {
            emit_block(eb, out, lbl, locals, fnp, le);
        }
        l!("_endif{n}:");
    } else if let Expr::Binary(
        op @ (crate::ast::BinOp::Lt
        | crate::ast::BinOp::Le
        | crate::ast::BinOp::Gt
        | crate::ast::BinOp::Ge),
        lhs,
        rhs,
    ) = cond
    {
        // Ordered comparison, unsigned 8-bit. One subtraction answers all four: `subwf f, w`
        // computes f - W, so with lhs stashed and rhs in W the carry is set iff lhs >= rhs (no
        // borrow) and Z is set iff they are equal. `>` and `<=` need both flags, since they are
        // the strict/non-strict halves that `>=` alone cannot tell apart.
        eval_to_w(lhs, out, locals, fnp);
        l!("        movwf   0x7D            ; lhs of the comparison");
        eval_to_w(rhs, out, locals, fnp);
        l!("        subwf   0x7D, w         ; lhs - rhs: C iff lhs >= rhs, Z iff equal");
        match op {
            // lhs < rhs: C clear. Skip the then-branch when C is set.
            crate::ast::BinOp::Lt => {
                l!("        btfsc   STATUS, 0");
                l!("        goto    _else{n}");
            }
            // lhs >= rhs: C set.
            crate::ast::BinOp::Ge => {
                l!("        btfss   STATUS, 0");
                l!("        goto    _else{n}");
            }
            // lhs > rhs: C set AND Z clear -- greater, and not equal.
            crate::ast::BinOp::Gt => {
                l!("        btfss   STATUS, 0");
                l!("        goto    _else{n}");
                l!("        btfsc   STATUS, 2       ; equal is not greater");
                l!("        goto    _else{n}");
            }
            // lhs <= rhs: C clear OR Z set.
            _ => {
                l!("        btfsc   STATUS, 2       ; equal counts as <=");
                l!("        goto    _then{n}");
                l!("        btfsc   STATUS, 0");
                l!("        goto    _else{n}");
                l!("_then{n}:");
            }
        }
        emit_block(then_b, out, lbl, locals, fnp, le);
        l!("        goto    _endif{n}");
        l!("_else{n}:");
        if let Some(eb) = else_b {
            emit_block(eb, out, lbl, locals, fnp, le);
        }
        l!("_endif{n}:");
    } else {
        // LOUD. This used to emit a comment and then NOTHING -- no then-branch, no else-branch:
        // the whole `if` vanished from the .hex, and the compiler exited 0. `if temp > 80 {
        // stop() }` compiled to a program that never stops. Silence about a condition is worse
        // than silence about an operator, because what disappears is the decision itself.
        panic!(
            "PIC16 codegen cannot emit this condition yet: it supports `==`, `!=`, `<`, `<=`, \
             `>` and `>=` between 8-bit values. Rewrite the condition with those, rather than \
             have the `if` silently disappear."
        );
    }
}

/// Emits a call in statement position: `poke8`, `delay`, `serial_init`, `serial_putc`, and a
/// bare `serial_getc()` (value discarded).
fn emit_call(
    e: &Expr,
    out: &mut String,
    locals: &HashMap<String, u8>,
    fnp: &HashMap<String, Vec<u8>>,
) {
    macro_rules! l {
        ($($a:tt)*) => {{ out.push_str(&format!($($a)*)); out.push('\n'); }};
    }
    let Some((name, args)) = as_call(e) else {
        l!("        ; (unsupported expression omitted in Phase 1b)");
        return;
    };
    match (name, args.len()) {
        // A user-defined function wins over a same-named backend intrinsic (so a
        // `provides Serial for pic16` written in Sond is dispatched with proper
        // argument passing, not the intrinsic's W convention).
        (name, _) if fnp.contains_key(name) => emit_user_call(name, args, out, locals, fnp),
        ("poke8", 2) => match (const8(&args[0].value), const8(&args[1].value)) {
            (Some(r), Some(v)) => {
                l!("        banksel 0x{r:02X}");
                l!("        movlw   0x{v:02X}");
                l!("        movwf   0x{r:02X}");
            }
            // Constant register, RUNTIME value: evaluate the value into W (banksel
            // is bit-ops on STATUS, so W survives), then store it. The register
            // address must still be a constant so we can bank-select it.
            (Some(r), None) => {
                eval_to_w(&args[1].value, out, locals, fnp);
                l!("        banksel 0x{r:02X}");
                l!("        movwf   0x{r:02X}");
            }
            _ => l!("        ; poke8 needs a constant register in Phase 1b"),
        },
        ("delay", 0) => l!("        call    delay"),
        ("delay_loop", 1) => match const8(&args[0].value) {
            Some(n) => {
                l!("        movlw   0x{:02X}", n & 0xFF);
                l!("        call    _delayw");
            }
            None => l!("        ; delay_loop needs a constant count in Phase 1b"),
        },
        ("serial_init", 0) => l!("        call    serial_init"),
        ("serial_getc", 0) => l!("        call    serial_getc"),
        ("serial_putc", 1) => {
            eval_to_w(&args[0].value, out, locals, fnp);
            l!("        call    serial_putc");
        }
        _ => l!("        ; (unsupported call `{name}` in Phase 1b)"),
    }
}

