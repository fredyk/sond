#!/usr/bin/env bash
# Build the compact Sond reference at ~/.local/share/sond/Sond.md.
#
# This bundle is the ONLY language knowledge given to example-writing AI workers
# (qwen3.6) during validation: they learn Sond from the docs, exactly like a real
# user would, NEVER from the compiler source. Reading the source would cheat the
# oracle test (they could reverse-engineer what the compiler accepts).
#
# The design RFCs are large and aspirational; feeding all of them to a small model
# drowns the practical surface. So the bundle includes ONLY the regions each doc
# marks for it, with a pair of HTML-comment markers that tell this tool what goes
# in and what does not:
#
#     <!-- SOND-MD-BEGIN -->   ... included verbatim ...   <!-- SOND-MD-END -->
#
# Text outside those markers (design rationale, history, open questions) is left
# out. The result is HARD-CAPPED: if it exceeds the byte budget the build FAILS,
# so Sond.md can never silently grow back into a wall of text.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
DOCS="$REPO/docs"
# Output path: ~/.local/share/sond/Sond.md by default; override with SOND_MD_OUT (the release
# packager points it at a staging dir).
OUT="${SOND_MD_OUT:-$HOME/.local/share/sond/Sond.md}"
OUT_DIR="$(dirname "$OUT")"
BUDGET=12000 # bytes; Sond.md must stay under this
mkdir -p "$OUT_DIR"

# Docs are scanned in this order; each contributes only its marked regions. A doc
# with no markers contributes nothing (it is design/context, not user reference).
ORDER=(
  implemented-language-surface.md
  rfc-0002-idiom-go.md
  rfc-0003-target-profiles.md
  rfc-0006-package-format.md
)

# Extract the inclusive content of every SOND-MD-BEGIN..END block in a file.
extract_marked() {
  awk '
    /<!--[[:space:]]*SOND-MD-BEGIN[[:space:]]*-->/ { on=1; next }
    /<!--[[:space:]]*SOND-MD-END[[:space:]]*-->/   { on=0; next }
    on { print }
  ' "$1"
}

tmp="$(mktemp)"
{
  echo "# Sond: Language Reference (compact)"
  echo
  echo "> The complete, current reference for writing Sond programs. Generated by"
  echo "> \`tools/build-docs.sh\` from the marked sections of the design docs."
  echo
  for f in "${ORDER[@]}"; do
    path="$DOCS/$f"
    [ -f "$path" ] || continue
    marked="$(extract_marked "$path")"
    [ -n "$marked" ] || continue
    printf '%s\n' "$marked"
    echo
  done
} >"$tmp"

bytes="$(wc -c <"$tmp")"
if [ "$bytes" -gt "$BUDGET" ]; then
  rm -f "$tmp"
  echo "build-docs: FAIL: Sond.md would be ${bytes} bytes (> ${BUDGET})." >&2
  echo "  Trim the marked SOND-MD regions in docs/ until the bundle fits." >&2
  exit 1
fi

mv "$tmp" "$OUT"
echo "sond: wrote ${bytes}/${BUDGET} bytes to ${OUT}"
